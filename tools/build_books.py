"""Build data/books.js for the app from tools/books_source.json.

For each book it looks up a cover on Open Library (free, no key) by the
English title and author, and remembers the answer in tools/covers_cache.json
so the lookup runs only once per book.

A book can override the lookup with "cover": <Open Library cover id>, or
"cover": null to use the app's drawn placeholder cover.

Usage:
    python3 tools/build_books.py            # look up only books not in the cache
    python3 tools/build_books.py --refresh  # look everything up again
"""

import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "books_source.json"
CACHE = ROOT / "tools" / "covers_cache.json"
OUT = ROOT / "data" / "books.js"

SEARCH_URL = "https://openlibrary.org/search.json"
USER_AGENT = "ma-hapaam-book-app/1.0 (personal reading app)"


def normalize(text):
    return re.sub(r"[^a-z0-9]", "", text.lower())


def search(**params):
    params.update(limit=10, fields="title,author_name,cover_i,edition_count")
    url = f"{SEARCH_URL}?{urllib.parse.urlencode(params)}"
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=20) as resp:
        return json.load(resp).get("docs", [])


def lookup_cover(title, author):
    """Return an Open Library cover id for the book, or None."""
    wanted = normalize(title)
    surname = normalize(author.split()[-1])
    most_published = lambda docs: max(docs, key=lambda d: d.get("edition_count", 0))["cover_i"]

    # 1. Exact English title by this author; the most-published edition is
    #    usually the well-known cover.
    docs = search(title=title, author=author)
    matches = [d for d in docs if d.get("cover_i") and normalize(d.get("title", "")) == wanted]
    if not matches:
        matches = [d for d in docs if d.get("cover_i") and wanted in normalize(d.get("title", ""))]
    if matches:
        return most_published(matches)

    # 2. Translated books are often listed under their original title, so do a
    #    free-text search and accept a result by the same author.
    docs = search(q=f"{title} {author}")
    matches = [d for d in docs if d.get("cover_i") and
               any(surname in normalize(a) for a in d.get("author_name", []))]
    return most_published(matches) if matches else None


def short_summary(text, max_sentences=3):
    """Keep only the first 2-3 sentences of an official description (fewer spoilers)."""
    sentences = re.split(r"(?<=[.!?])\s+", text.strip())
    return " ".join(sentences[:max_sentences])


def main():
    refresh = "--refresh" in sys.argv
    books = json.loads(SOURCE.read_text(encoding="utf-8"))
    cache = {} if refresh or not CACHE.exists() else json.loads(CACHE.read_text(encoding="utf-8"))

    ids = [b["id"] for b in books]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        sys.exit(f"Duplicate book ids: {', '.join(sorted(dupes))}")

    for book in books:
        if "cover" in book or book["id"] in cache:
            continue
        try:
            cache[book["id"]] = lookup_cover(book["en"], book["enAuthor"])
        except Exception as err:  # network trouble: skip, try again next run
            print(f"  ! {book['title']}: {err}")
            continue
        status = "found" if cache[book["id"]] else "no cover"
        print(f"  {book['en']}: {status}")
        time.sleep(0.5)  # be polite to the free service

    CACHE.write_text(json.dumps(cache, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    out = []
    for book in books:
        entry = {k: v for k, v in book.items() if k != "cover"}
        entry["cover"] = book["cover"] if "cover" in book else cache.get(book["id"])
        if len(re.findall(r"[.!?]", entry["summary"])) > 3:
            entry["summary"] = short_summary(entry["summary"])
        out.append(entry)

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by tools/build_books.py from tools/books_source.json. Do not edit by hand.\n"
        "window.BOOKS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    missing = [b["title"] for b in out if not b["cover"]]
    print(f"Wrote {len(out)} books to {OUT.relative_to(ROOT)}"
          + (f" ({len(missing)} without a cover: {', '.join(missing)})" if missing else ""))


if __name__ == "__main__":
    main()
